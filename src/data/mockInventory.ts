export const getDaysUntilExpiry = (expiryDate: string): number => {
  const today = new Date('2026-08-15');
  const expiry = new Date(expiryDate);
  const diff = expiry.getTime() - today.getTime();
  return Math.floor(diff / (1000 * 60 * 60 * 24));
};

export const isRowCritical = (medicine: Medicine): boolean => {
  const daysToExpiry = getDaysUntilExpiry(medicine.expiryDate);
  return medicine.currentStock < medicine.threshold || daysToExpiry <= 30;
};